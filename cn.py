# EMBEDDER (MiniLM; offline hashing fallback only if it cannot load)
# =====================================================================
class _HashEncoder:
    def __init__(self, n_features: int = 512):
        from sklearn.feature_extraction.text import HashingVectorizer
        self._vec = HashingVectorizer(n_features=n_features, analyzer="word", ngram_range=(1, 2),
                                      norm="l2", alternate_sign=False, token_pattern=r"(?u)\b\w+\b")
        self.n = n_features

    def encode(self, texts, normalize_embeddings=True, show_progress_bar=False):
        mat = self._vec.transform(list(texts)).toarray().astype(np.float64)
        norms = np.linalg.norm(mat, axis=1, keepdims=True)
        norms[norms == 0] = 1.0
        return mat / norms


class Embedder:
    def __init__(self, model_name: str = MODEL_NAME):
        self._cache = {}
        try:
            from sentence_transformers import SentenceTransformer
            self._model = SentenceTransformer(model_name)
            self.backend = f"MiniLM ({model_name})"
        except Exception as exc:
            print(f"[WARNING] could not load '{model_name}' ({type(exc).__name__}); "
                  f"using the offline hashing fallback. Results will differ from MiniLM.")
            self._model = _HashEncoder()
            self.backend = "offline hashing fallback"
        self.dim = int(self._model.encode(["probe"]).shape[1])

    def encode(self, texts: List[str]) -> np.ndarray:
        missing = [t for t in dict.fromkeys(texts) if t not in self._cache]
        if missing:
            vecs = np.asarray(self._model.encode(missing, normalize_embeddings=True,
                                                 show_progress_bar=False), dtype=np.float64)
            for t, v in zip(missing, vecs):
                self._cache[t] = v
        return np.vstack([self._cache[t] for t in texts])


