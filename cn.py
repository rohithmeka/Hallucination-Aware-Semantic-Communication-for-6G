# 6G PHY PRIMITIVES (verified in the previous version: AWGN BER matches Q(sqrt(SNR)))
# =====================================================================
C_MPS = 299_792_458.0
NOISE_DENSITY_DBM_HZ = -174.0
CRC_BITS = 16
CONSTRAINT_LEN = 7
N_STATES = 1 << (CONSTRAINT_LEN - 1)   # 64
_G0, _G1 = 0o133, 0o171


def _parity(x: int) -> int:
    return bin(int(x)).count("1") & 1


def qam_constellation(bits_per_symbol: int) -> np.ndarray:
    """Unit-average-energy Gray constellation indexed by natural bit label
    (MSB first). QPSK (2) and square 16-QAM (4). Positive LLR = bit 0."""
    if bits_per_symbol == 2:
        pts = []
        for label in range(4):
            b0, b1 = (label >> 1) & 1, label & 1
            pts.append(((1.0 - 2.0 * b0) + 1j * (1.0 - 2.0 * b1)) / math.sqrt(2.0))
        return np.asarray(pts, dtype=np.complex128)
    if bits_per_symbol == 4:
        levels = np.array([3.0, 1.0, -3.0, -1.0])   # Gray: 00,01,10,11
        pts = []
        for label in range(16):
            pts.append((levels[(label >> 2) & 3] + 1j * levels[label & 3]) / math.sqrt(10.0))
        return np.asarray(pts, dtype=np.complex128)
    raise ValueError("bits_per_symbol must be 2 (QPSK) or 4 (16-QAM).")


def demap_llr(y, noise_var, pts, bits_per_symbol: int) -> np.ndarray:
    """Exact log-sum soft demapper; positive LLR = bit 0.
    noise_var = E[|complex noise|^2] after equalisation."""
    y = np.asarray(y, dtype=np.complex128).reshape(-1)
    pts = np.asarray(pts, dtype=np.complex128).reshape(-1)
    nv = np.asarray(noise_var, dtype=float)
    nv = np.full(y.size, float(nv)) if nv.ndim == 0 else np.broadcast_to(nv.reshape(-1), (y.size,))
    if np.any(~np.isfinite(nv)) or np.any(nv <= 0):
        raise ValueError("noise_var must contain finite positive values")
    if len(pts) != (1 << bits_per_symbol):
        raise ValueError("Constellation size does not match bits_per_symbol")
    scaled = -(np.abs(y[:, None] - pts[None, :]) ** 2) / nv[:, None]
    labels = np.arange(len(pts), dtype=np.uint32)
    out = np.empty((len(y), bits_per_symbol), dtype=float)
    for bitpos in range(bits_per_symbol):
        shift = bits_per_symbol - 1 - bitpos
        is_zero = ((labels >> shift) & 1) == 0
        l0 = np.logaddexp.reduce(scaled[:, is_zero], axis=1)
        l1 = np.logaddexp.reduce(scaled[:, ~is_zero], axis=1)
        out[:, bitpos] = np.clip(l0 - l1, -60.0, 60.0)
    return out.reshape(-1)


# --- convolutional code (vectorised trellis) ---------------------------
_REGS = np.arange(1 << CONSTRAINT_LEN)
_OUT0 = np.array([_parity(r & _G0) for r in _REGS], dtype=np.uint8)
_OUT1 = np.array([_parity(r & _G1) for r in _REGS], dtype=np.uint8)
_SIGN0 = 1.0 - 2.0 * _OUT0
_SIGN1 = 1.0 - 2.0 * _OUT1
_NS = np.arange(N_STATES)
_PREV0 = _NS >> 1
_PREV1 = (_NS >> 1) | (N_STATES >> 1)
_BIT = _NS & 1
_REG0 = (_PREV0 << 1) | _BIT
_REG1 = (_PREV1 << 1) | _BIT


def conv_encode(bits, terminate: bool = False) -> np.ndarray:
    """Rate-1/2, K=7 encoder (133,171 octal). terminate=True appends 6 zero
    tail bits so the trellis returns to state 0."""
    b = np.asarray(bits, dtype=np.uint8).reshape(-1)
    if np.any(b > 1):
        raise ValueError("bits must contain only 0 and 1")
    if terminate:
        b = np.concatenate([b, np.zeros(CONSTRAINT_LEN - 1, dtype=np.uint8)])
    state, mask = 0, N_STATES - 1
    out = np.empty(2 * b.size, dtype=np.uint8)
    for i, bit in enumerate(b):
        reg = (state << 1) | int(bit)
        out[2 * i] = _OUT0[reg]
        out[2 * i + 1] = _OUT1[reg]
        state = reg & mask
    return out


def viterbi_decode(llr, terminated: bool = False) -> np.ndarray:
    """Soft-decision Viterbi (positive LLR = bit 0). If terminated=True the
    path is forced to end in state 0 and the 6 tail bits are removed."""
    v = np.asarray(llr, dtype=float).reshape(-1)
    if v.size % 2:
        raise ValueError("Viterbi input length must be even")
    if not np.all(np.isfinite(v)):
        raise ValueError("LLRs must be finite")
    n = v.size // 2
    if terminated and n < CONSTRAINT_LEN - 1:
        raise ValueError("Terminated block shorter than the tail")
    if n == 0:
        return np.zeros(0, dtype=np.uint8)

    bm = v[0::2, None] * _SIGN0[None, :] + v[1::2, None] * _SIGN1[None, :]   # (n,128)
    metrics = np.full(N_STATES, -np.inf)
    metrics[0] = 0.0
    from_hi = np.zeros((n, N_STATES), dtype=bool)
    for t in range(n):
        ca = metrics[_PREV0] + bm[t, _REG0]
        cb = metrics[_PREV1] + bm[t, _REG1]
        pick = cb > ca
        metrics = np.where(pick, cb, ca)
        from_hi[t] = pick

    state = 0 if terminated else int(np.argmax(metrics))
    decoded = np.empty(n, dtype=np.uint8)
    for t in range(n - 1, -1, -1):
        decoded[t] = state & 1
        state = int(_PREV1[state] if from_hi[t, state] else _PREV0[state])
    return decoded[:n - (CONSTRAINT_LEN - 1)] if terminated else decoded


# --- CRC, quantisation, bit packing ------------------------------------
def _crc16_ccitt(data_bits) -> np.ndarray:
    bits = np.asarray(data_bits, dtype=np.uint8).reshape(-1)
    crc = 0xFFFF
    for bit in bits:
        feedback = ((crc >> 15) & 1) ^ int(bit)
        crc = (crc << 1) & 0xFFFF
        if feedback:
            crc ^= 0x1021
    return np.array([(crc >> s) & 1 for s in range(15, -1, -1)], dtype=np.uint8)


def _append_crc(payload_bits) -> np.ndarray:
    p = np.asarray(payload_bits, dtype=np.uint8).reshape(-1)
    return np.concatenate([p, _crc16_ccitt(p)])


def _check_crc(frame_bits) -> bool:
    f = np.asarray(frame_bits, dtype=np.uint8).reshape(-1)
    if f.size < CRC_BITS:
        return False
    return bool(np.array_equal(_crc16_ccitt(f[:-CRC_BITS]), f[-CRC_BITS:]))




def _bits_to_symbols(bits, bits_per_symbol: int, pts):
    b = np.asarray(bits, dtype=np.uint8).reshape(-1)
    pad = (-b.size) % bits_per_symbol
    if pad:
        b = np.concatenate([b, np.zeros(pad, dtype=np.uint8)])
    groups = b.reshape(-1, bits_per_symbol).astype(np.uint32)
    weights = 1 << np.arange(bits_per_symbol - 1, -1, -1, dtype=np.uint32)
    return np.asarray(pts)[groups @ weights], pad


def ints_to_bits(values, width: int) -> np.ndarray:
    v = np.asarray(values, dtype=np.uint32).reshape(-1)
    shifts = np.arange(width - 1, -1, -1, dtype=np.uint32)
    return ((v[:, None] >> shifts[None, :]) & 1).astype(np.uint8).reshape(-1)


def bits_to_ints(bits, width: int) -> np.ndarray:
    b = np.asarray(bits, dtype=np.uint8).reshape(-1)
    if b.size % width:
        raise ValueError("bit count not divisible by width")
    shifts = np.arange(width - 1, -1, -1, dtype=np.uint32)
    return np.sum(b.reshape(-1, width).astype(np.uint32) << shifts[None, :], axis=1, dtype=np.uint32)


def quantise(x, width: int, rng_abs: float) -> np.ndarray:
    """Mid-tread uniform quantiser: 0.0 is exactly representable (sparse-safe)."""
    x = np.asarray(x, dtype=float).reshape(-1)
    levels = (1 << width) - 2
    return np.rint((np.clip(x, -rng_abs, rng_abs) + rng_abs) / (2 * rng_abs) * levels).astype(np.uint32)


def dequantise(q, width: int, rng_abs: float) -> np.ndarray:
    levels = (1 << width) - 2
    return (2.0 * np.asarray(q, dtype=float) / levels - 1.0) * rng_abs


