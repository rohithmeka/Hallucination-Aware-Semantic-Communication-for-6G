# NOISE-ONLY DRIFT TEST (can noise alone turn Room 3 into Room 4?)
# =====================================================================
def run_drift(embedder: Embedder, text: str, levels=(0, -10, -15, -20, -25), trials: int = 100,
              seed: int = 7):
    corpus = make_corpus(300, seed=2026)
    kb = KnowledgeBase(embedder, corpus + [text])
    neighbours = {v["text"] for v in enumerate_variants(text)}
    print("=" * 96)
    print(f" NOISE-ONLY DRIFT   sent: '{text}'   {trials} trials/level, clean link, NO sender error")
    print("=" * 96)
    print(f" {'feature SNR':>11} {'unchanged':>10} {'-> neighbour':>13} {'-> other':>9} "
          f"{'checksum flags wrong':>21} {'silent-wrong':>13}")
    for k, lvl in enumerate(levels):
        sl = SemanticLink(embedder, LinkConfig(fading="awgn", snr_override_db=40.0, speed_mps=0.0),
                          seed=seed + k)
        same = nb = oth = flagged = 0
        wrong_c = Counter()
        for _ in range(trials):
            dec = receive(sl.send(text, text, kb, 10.0, sem_noise_db=float(lvl)), kb)
            if dec.text == text:
                same += 1
                continue
            nb += dec.text in neighbours
            oth += dec.text not in neighbours
            flagged += int(not dec.checksum_ok)
            wrong_c[dec.text] += 1
        wrong = nb + oth
        fl = f"{100*flagged/wrong:.0f}%" if wrong else "n/a"
        print(f" {lvl:>8} dB {100*same/trials:9.0f}% {100*nb/trials:12.0f}% {100*oth/trials:8.0f}% "
              f"{fl:>21} {100*(wrong-flagged)/trials:12.0f}%")
        if wrong_c:
            print(f"             most common wrong decode: '{wrong_c.most_common(1)[0][0]}'")
    print("\n silent-wrong = decoded wrong AND checksum matched. The checksum is computed from the")
    print(" intended text, so any decode that differs from it is flagged.")


