# SELF-TEST
# =====================================================================
def run_selftest(embedder: Optional[Embedder] = None) -> bool:
    print("=" * 96)
    print(" SELF-TEST")
    print("=" * 96)
    results = []

    def check(name, ok, extra=""):
        results.append(bool(ok))
        print(f"  [{'PASS' if ok else 'FAIL'}] {name}{(' ' + extra) if extra else ''}")

    rng = np.random.default_rng(1)
    bits = rng.integers(0, 2, 400).astype(np.uint8)
    check("Viterbi noiseless round trip",
          np.array_equal(viterbi_decode(np.where(conv_encode(bits, terminate=True) == 0, 4.0, -4.0),
                                        terminated=True), bits))
    coded = conv_encode(bits, terminate=True)
    llr = np.where(coded == 0, 4.0, -4.0)
    llr[rng.choice(coded.size, 20, replace=False)] *= -1
    check("Viterbi corrects 20 flipped coded bits (about 2.5%)",
          np.array_equal(viterbi_decode(llr, terminated=True), bits))

    for m, nm in ((2, "QPSK"), (4, "16-QAM")):
        pts = qam_constellation(m)
        labels = np.arange(1 << m, dtype=np.uint32)
        b = ((labels[:, None] >> np.arange(m - 1, -1, -1)) & 1).astype(np.uint8)
        rec = (demap_llr(pts[labels], np.full(len(pts), 1e-4), pts, m) < 0).astype(np.uint8).reshape(-1, m)
        check(f"{nm} Gray mapping + unit energy", np.array_equal(b, rec) and abs(np.mean(np.abs(pts) ** 2) - 1) < 1e-12)

    fr = _append_crc(rng.integers(0, 2, 200).astype(np.uint8))
    bad = fr.copy()
    bad[17] ^= 1
    check("CRC accepts clean frame, rejects 1-bit error", _check_crc(fr) and not _check_crc(bad))

    x = rng.uniform(-0.4, 0.4, 200)
    xr = dequantise(quantise(x, BITS_PER_DIM, 0.5), BITS_PER_DIM, 0.5)
    z = dequantise(quantise(np.zeros(5), BITS_PER_DIM, 0.5), BITS_PER_DIM, 0.5)
    check("Quantiser: error <= half step and 0.0 exact",
          float(np.max(np.abs(xr - x))) <= 0.5 / ((1 << BITS_PER_DIM) - 2) * 1.0 + 1e-9 and np.all(z == 0))
    rt = bits_to_ints(ints_to_bits(np.arange(256), 8), 8)
    check("Bit packing round trip", np.array_equal(rt, np.arange(256)))

    check("Checksum deterministic", np.array_equal(fact_checksum("Fire detected in Room 3."),
                                                   fact_checksum("Fire detected in Room 3.")))
    check("Checksum: Room 3 vs Room 4 differ", not np.array_equal(fact_checksum("Fire detected in Room 3."),
                                                                   fact_checksum("Fire detected in Room 4.")))
    check("Checksum: open vs closed differ", not np.array_equal(fact_checksum("The lab door is open."),
                                                                 fact_checksum("The lab door is closed.")))
    check("Checksum: non-allergic vs allergic differ",
          not np.array_equal(fact_checksum("Patient is allergic to penicillin."),
                             fact_checksum("Patient is non-allergic to penicillin.")))
    check("Checksum ignores case (same template, same fields)",
          np.array_equal(fact_checksum("Fire detected in Room 3."), fact_checksum("FIRE DETECTED IN ROOM 3.")))
    check("Subject/object order preserved: 'Dog bites man' != 'Man bites dog'",
          not np.array_equal(fact_checksum("Dog bites man."), fact_checksum("Man bites dog.")))
    check("Structured fields: 'allergic to penicillin' != 'allergic to aspirin'",
          not np.array_equal(fact_checksum("Patient is allergic to penicillin."),
                             fact_checksum("Patient is allergic to aspirin.")))
    check("Harmless re-encoding of the SAME template+fields -> same checksum (no false alarm)",
          np.array_equal(fact_checksum("The lab door is open."), fact_checksum("the lab door is open.")))

    if embedder is None:
        embedder = Embedder()
    corpus = make_corpus(60, seed=1)
    kb = KnowledgeBase(embedder, corpus)
    clean = LinkConfig(fading="awgn", snr_override_db=40.0, speed_mps=0.0)
    sent = "Fire detected in Room 3."
    dec = receive(SemanticLink(embedder, clean, seed=3).send(sent, sent, kb, 1.0), kb)
    check("Clean end-to-end link: decoded correctly, CRC ok, checksum match",
          dec.text == sent and dec.crc_ok and dec.checksum_ok, f"(decoded='{dec.text}')")
    dec = receive(SemanticLink(embedder, clean, seed=3).send(sent, "Fire detected in Room 4.", kb, 1.0), kb)
    check("Sender error (Room 4 sent for Room 3) is caught by checksum",
          (not dec.checksum_ok) and dec.crc_ok, f"(decoded='{dec.text}')")

    sims = []
    for i, snr in enumerate((6, 8)):
        l = SixGLink(LinkConfig(fading="awgn", snr_override_db=float(snr), speed_mps=0.0, bits_per_symbol=2), seed=50 + i)
        b = np.random.default_rng(60 + i).integers(0, 2, 40000).astype(np.uint8)
        _, st = l.send(b, 1.0)
        sims.append((st.ber, 0.5 * math.erfc(math.sqrt(10 ** (snr / 10)) / math.sqrt(2))))
    check("AWGN QPSK BER within 35% of theory at 6 and 8 dB",
          all(abs(s - t) / t < 0.35 for s, t in sims), "(" + ", ".join(f"{s:.2e}/{t:.2e}" for s, t in sims) + ")")

    allok = all(results)
    print("-" * 96)
    print(f"  SELF-TEST: {sum(results)}/{len(results)} -> {'ALL GOOD' if allok else 'FAILED'}")
    return allok


