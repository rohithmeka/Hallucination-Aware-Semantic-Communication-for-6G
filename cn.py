def make_corpus(n: int = 300, seed: int = 0) -> List[str]:
    rng = np.random.default_rng(seed)
    out, seen, tries = [], set(), 0
    while len(out) < n and tries < n * 50:
        tries += 1
        tpl, slots = _TEMPLATES[int(rng.integers(len(_TEMPLATES)))]
        vals = {k: str(rng.choice(list(v))) for k, v in slots.items()}
        s = tpl.format(**vals)
        if s not in seen:
            seen.add(s)
            out.append(s)
    return out


def split_corpus(corpus: List[str], seed: int) -> Tuple[List[str], List[str]]:
    idx = np.random.default_rng(seed).permutation(len(corpus))
    cut = len(corpus) // 2
    return [corpus[i] for i in idx[:cut]], [corpus[i] for i in idx[cut:]]


