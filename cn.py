# KNOWLEDGE BASE (the receiver's known messages; built from the corpus + variants)
# =====================================================================
def _cos_rows(x, mat):
    x = np.asarray(x, dtype=np.float64).reshape(-1)
    nx = float(np.linalg.norm(x))
    if nx == 0 or not np.isfinite(nx):
        return np.full(mat.shape[0], -1.0)
    nm = np.linalg.norm(mat, axis=1)
    nm = np.where(nm == 0, 1.0, nm)
    return (mat @ x) / (nm * nx)


class KnowledgeBase:
    def __init__(self, embedder: Embedder, sentences: List[str]):
        texts, seen = [], set()
        for s in sentences:
            for t in [s] + [v["text"] for v in enumerate_variants(s)]:
                if t not in seen:
                    seen.add(t)
                    texts.append(t)
        self.texts = texts
        self.emb = embedder.encode(texts)
        peak = float(np.max(np.abs(self.emb)))
        self.quant_range = min(1.0, max(0.05, math.ceil(peak * 1.05 * 100) / 100))

    def match(self, vec) -> Tuple[str, float, float, float]:
        sims = _cos_rows(vec, self.emb)
        order = np.argsort(sims)[::-1]
        i1, i2 = int(order[0]), int(order[1])
        return self.texts[i1], float(sims[i1]), float(sims[i2]), float(sims[i1] - sims[i2])


# =====================================================================
# 6G LINK (generic bit pipe: CRC -> FEC -> QAM -> channel -> demap -> Viterbi -> CRC)
# =====================================================================
@dataclass
class LinkConfig:
    fc_ghz: float = 140.0
    bandwidth_hz: float = 400e6
    n_tx: int = 64
    speed_mps: float = 8.3
    bits_per_symbol: int = 2                 # 2 = QPSK, 4 = 16-QAM
    tx_power_dbm: float = 10.0
    noise_figure_db: float = 7.0
    nlos_loss_db: float = 20.0
    shadow_los_db: float = 4.0
    shadow_nlos_db: float = 7.0
    rician_k_db: float = 8.0
    los_decay_m: float = 80.0
    fading: str = "auto"                     # auto | rician | rayleigh | awgn
    snr_override_db: Optional[float] = None  # fixed mean SNR (bypasses the link budget)
    extra_loss_db: float = 0.0


@dataclass
class PhyStats:
    los: bool
    snr_db: float
    ber: float          # pre-FEC hard-decision BER
    crc_ok: bool
    symbols: int
    duration_s: float


class SixGLink:
    def __init__(self, cfg: LinkConfig, seed: Optional[int] = None):
        if cfg.bits_per_symbol not in (2, 4):
            raise ValueError("bits_per_symbol must be 2 or 4")
        self.cfg = cfg
        self.rng = np.random.default_rng(seed)
        self.pts = qam_constellation(cfg.bits_per_symbol)

    def _large_scale(self, d: float):
        c = self.cfg
        if c.fading == "auto":
            los = bool(self.rng.random() < math.exp(-d / c.los_decay_m))
        else:
            los = c.fading in ("rician", "awgn")
        fspl = 20 * math.log10(4 * math.pi * d * c.fc_ghz * 1e9 / C_MPS)
        shadow = float(self.rng.normal(0.0, c.shadow_los_db if los else c.shadow_nlos_db))
        rx_dbm = (c.tx_power_dbm + 10 * math.log10(c.n_tx) - fspl
                  - (0.0 if los else c.nlos_loss_db) - c.extra_loss_db - shadow)
        noise_dbm = NOISE_DENSITY_DBM_HZ + 10 * math.log10(c.bandwidth_hz) + c.noise_figure_db
        snr = rx_dbm - noise_dbm if c.snr_override_db is None else float(c.snr_override_db)
        return los, snr

    def _fade(self, los: bool) -> complex:
        c = self.cfg
        if c.fading == "awgn":
            return 1.0 + 0.0j
        if los:
            k = 10 ** (c.rician_k_db / 10)
            spec = math.sqrt(k / (k + 1)) * np.exp(1j * self.rng.uniform(0, 2 * math.pi))
            scat = (self.rng.normal() + 1j * self.rng.normal()) / math.sqrt(2 * (k + 1))
            return complex(spec + scat)
        return complex((self.rng.normal() + 1j * self.rng.normal()) / math.sqrt(2))

    def send(self, payload: np.ndarray, distance_m: float) -> Tuple[np.ndarray, PhyStats]:
        if not (np.isfinite(distance_m) and distance_m > 0):
            raise ValueError("distance_m must be finite and positive")
        c = self.cfg
        frame = _append_crc(payload)
        coded = conv_encode(frame, terminate=True)
        tx, pad = _bits_to_symbols(coded, c.bits_per_symbol, self.pts)

        los, snr_db = self._large_scale(distance_m)
        h0 = self._fade(los)
        dopp_max = c.speed_mps * c.fc_ghz * 1e9 / C_MPS
        dopp = 0.0 if c.fading == "awgn" else dopp_max * math.cos(self.rng.uniform(0, 2 * math.pi))
        t = np.arange(tx.size, dtype=float) / c.bandwidth_hz
        h_t = h0 * np.exp(1j * 2 * math.pi * dopp * t)
        nvar = 10 ** (-float(np.clip(snr_db, -50, 50)) / 10)
        noise = math.sqrt(nvar / 2) * (self.rng.normal(size=tx.size) + 1j * self.rng.normal(size=tx.size))
        rx = h_t * tx + noise

        h_eff = h0 if abs(h0) > 1e-9 else 1e-9 + 0j      # ideal first-symbol estimate
        llr = demap_llr(rx / h_eff, nvar / max(abs(h_eff) ** 2, 1e-12), self.pts, c.bits_per_symbol)
        if pad:
            llr = llr[:-pad]
        ber = float(np.mean((llr < 0).astype(np.uint8) != coded))
        dec = viterbi_decode(llr, terminated=True)
        dec = np.pad(dec, (0, max(0, frame.size - dec.size)))[:frame.size]
        crc_ok = bool(_check_crc(dec))
        duration = tx.size / c.bandwidth_hz + distance_m / C_MPS
        return dec[:-CRC_BITS], PhyStats(los, float(snr_db), ber, crc_ok, int(tx.size), float(duration))


# =====================================================================
# SEMANTIC TRANSMITTER / RECEIVER
# =====================================================================
@dataclass
class Received:
    emb: Optional[np.ndarray]
    checksum: Optional[np.ndarray]
    crc_ok: bool
    phy: Optional[PhyStats]
    lost: bool = False


class SemanticLink:
    def __init__(self, embedder: Embedder, cfg: LinkConfig, seed: Optional[int] = None,
                 outage_p: float = 0.0):
        self.embedder = embedder
        self.link = SixGLink(cfg, seed=seed)
        self.rng = np.random.default_rng(None if seed is None else seed + 101)
        self.outage_p = outage_p

    def send(self, intended: str, transmitted: str, kb: KnowledgeBase, distance_m: float,
             sem_noise_db: Optional[float] = None) -> Received:
        """intended = the meaning the sender wants delivered (its checksum is sent).
        transmitted = the text the (possibly hallucinating) encoder actually encodes."""
        if self.rng.random() < self.outage_p:
            return Received(None, None, False, None, lost=True)
        emb = self.embedder.encode([transmitted])[0]
        q = quantise(emb, BITS_PER_DIM, kb.quant_range)
        payload = np.concatenate([ints_to_bits(q, BITS_PER_DIM), fact_checksum(intended)])
        rx_payload, phy = self.link.send(payload, distance_m)
        n_emb = emb.size * BITS_PER_DIM
        rx_emb = dequantise(bits_to_ints(rx_payload[:n_emb], BITS_PER_DIM), BITS_PER_DIM, kb.quant_range)
        if sem_noise_db is not None:       # analog semantic-domain noise (drift test only)
            p = float(np.mean(rx_emb ** 2))
            if p > 0:
                rx_emb = rx_emb + self.rng.normal(0.0, math.sqrt(p / 10 ** (sem_noise_db / 10)), rx_emb.size)
        return Received(rx_emb, rx_payload[n_emb:], phy.crc_ok, phy)


@dataclass
class Decision:
    text: str
    sim1: float
    sim2: float
    margin: float
    crc_ok: bool
    checksum_ok: bool
    lost: bool = False


def receive(rx: Received, kb: KnowledgeBase) -> Decision:
    if rx.lost:
        return Decision("<packet lost>", 0.0, 0.0, 0.0, False, False, lost=True)
    text, s1, s2, m = kb.match(rx.emb)
    checksum_ok = bool(np.array_equal(fact_checksum(text), rx.checksum))
    return Decision(text, s1, s2, m, rx.crc_ok, checksum_ok)


# =====================================================================
# SEMANTIC CONSISTENCY VERIFIER (SCV): receiver-side rules
# =====================================================================
@dataclass(frozen=True)
class Rule:
    name: str
    crc: bool = False
    checksum: bool = False
    similarity: bool = False
    margin: bool = False


RULES = [
    Rule("S0 no verifier"),
    Rule("S1 CRC only", crc=True),
    Rule("S2 similarity", similarity=True),
    Rule("S3 similarity+margin", similarity=True, margin=True),
    Rule("S4 meaning checksum (recommended)", checksum=True),
    Rule("S5 CRC + checksum", crc=True, checksum=True),
    Rule("S6 all four signals", crc=True, checksum=True, similarity=True, margin=True),
]
RECOMMENDED = RULES[4]


@dataclass(frozen=True)
class Thresholds:
    sim: float = DEFAULT_SIM_THR
    margin: float = DEFAULT_MARGIN_THR


def assess(rule: Rule, d: Decision, th: Thresholds) -> Tuple[str, List[str]]:
    if d.lost:
        return "LOST", ["packet lost"]
    reasons = []
    if rule.crc and not d.crc_ok:
        reasons.append("PHY CRC failed")
    if rule.checksum and not d.checksum_ok:
        reasons.append("meaning checksum mismatch (decoded meaning != intended meaning)")
    if rule.similarity and d.sim1 < th.sim:
        reasons.append(f"low similarity {d.sim1:.3f} < {th.sim}")
    if rule.margin and d.margin < th.margin:
        reasons.append(f"ambiguous margin {d.margin:.3f} < {th.margin}")
    return ("HIGH" if reasons else "LOW"), reasons


# =====================================================================
# STATISTICS
# =====================================================================
def wilson(k: int, n: int, z: float = 1.96) -> Tuple[float, float]:
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    den = 1 + z * z / n
    cen = (p + z * z / (2 * n)) / den
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return (max(0.0, cen - half), min(1.0, cen + half))


@dataclass
class Trial:
    distance: float
    intended: str
    transmitted: str
    corrupted: bool
    dec: Decision
    los: bool
    snr_db: float
    ber: float

    @property
    def wrong(self) -> bool:
        return self.dec.text != self.intended


def score(trials: List[Trial], rule: Rule, th: Thresholds) -> dict:
    tp = fp = tn = fn = 0
    for t in trials:
        if t.dec.lost:
            continue
        flagged = assess(rule, t.dec, th)[0] == "HIGH"
        if t.wrong and flagged:
            tp += 1
        elif t.wrong:
            fn += 1
        elif flagged:
            fp += 1
        else:
            tn += 1
    n = tp + fp + tn + fn
    rec = tp / (tp + fn) if tp + fn else float("nan")
    fpr = fp / (fp + tn) if fp + tn else float("nan")
    prec = tp / (tp + fp) if tp + fp else float("nan")
    f1 = 2 * prec * rec / (prec + rec) if (prec == prec and rec == rec and prec + rec > 0) else float("nan")
    return {"n": n, "tp": tp, "fp": fp, "tn": tn, "fn": fn, "recall": rec, "fpr": fpr, "f1": f1,
            "silent": fn / n if n else float("nan"), "recall_ci": wilson(tp, tp + fn),
            "fpr_ci": wilson(fp, fp + tn)}


def calibrate(train: List[Trial]) -> Thresholds:
    """Choose (similarity, margin) maximising F1 of the similarity+margin rule on TRAIN trials.
    The checksum rule needs no threshold."""
    best, best_f1 = Thresholds(), -1.0
    for s in np.round(np.arange(0.50, 0.96, 0.05), 2):
        for m in (0.0, 0.01, 0.02, 0.05, 0.10):
            f1 = score(train, RULES[3], Thresholds(float(s), float(m)))["f1"]
            if f1 == f1 and f1 > best_f1 + 1e-12:
                best, best_f1 = Thresholds(float(s), float(m)), f1
    return best


# =====================================================================
# TRIAL GENERATION
# =====================================================================
def collect(sl: SemanticLink, kb: KnowledgeBase, sentences: List[str], distances, n_per_distance: int,
            corrupt_p: float, rng) -> List[Trial]:
    out = []
    for d in distances:
        for _ in range(n_per_distance):
            s = sentences[int(rng.integers(len(sentences)))]
            var = enumerate_variants(s)
            tx, corrupted = s, False
            if var and rng.random() < corrupt_p:
                tx, corrupted = var[int(rng.integers(len(var)))]["text"], True
            rx = sl.send(s, tx, kb, d)
            dec = receive(rx, kb)
            out.append(Trial(d, s, tx, corrupted, dec,
                             bool(rx.phy.los) if rx.phy else False,
                             rx.phy.snr_db if rx.phy else float("nan"),
                             rx.phy.ber if rx.phy else float("nan")))
    return out


