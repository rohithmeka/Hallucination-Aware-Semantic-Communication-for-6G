    p.add_argument("--experiment", action="store_true")
    p.add_argument("--drift", action="store_true", help="noise-only drift test on the text")
    p.add_argument("--selftest", action="store_true")
    p.add_argument("--trials", type=int, default=150)
    p.add_argument("--corrupt", type=float, default=0.5, help="sender-error probability (experiment)")
    p.add_argument("--seed", type=int, default=42)
