def _print_decision(label, intended, transmitted, rx, dec, th):
    print(f"\n[{label}]")
    print(f"    intended    : {intended}")
    print(f"    transmitted : {transmitted}" + ("   <- sender-side error" if transmitted != intended else ""))
    if rx.lost:
        print("    PHY         : packet lost")
    else:
        p = rx.phy
        print(f"    PHY         : {'LOS' if p.los else 'NLOS'} | SNR {p.snr_db:.1f} dB | pre-FEC BER {p.ber:.2e} | "
              f"CRC {'ok' if p.crc_ok else 'FAIL'} | {p.symbols} symbols | {p.duration_s*1e6:.2f} us")
    tag = "correct" if dec.text == intended else "WRONG"
    print(f"    decoded     : {dec.text}   [{tag}]")
    print(f"    checksum    : {'MATCH' if dec.checksum_ok else 'MISMATCH'}   "
          f"sim1={dec.sim1:.4f} margin={dec.margin:.4f}")
    risk, reasons = assess(RECOMMENDED, dec, th)
    print(f"    verdict     : {risk}" + (f"  ({'; '.join(reasons)})" if reasons else ""))


